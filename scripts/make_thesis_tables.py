# Day 9.1: the thesis's result tables and figures, generated from the results -- never typed.
#
#   python scripts/make_thesis_tables.py
#
# Reads results/summary.json (scripts/score.py), results/runs/, results/judged/ and
# eval/annotations.csv. Writes paper/tables/*.tex, paper/figures/fig_outcomes.pdf and
# paper/numbers.tex (\newcommand macros for the numbers quoted in the text). If a number
# changes, re-run score.py and this script, then rebuild the PDF.
import csv
import json
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from gea import config as cfg
from gea.metrics import center_inside, published
from gea.safeio import atomic_write_text, read_jsonl

ROOT = cfg.PROJECT_ROOT
TABLES, FIGURES = ROOT / "paper" / "tables", ROOT / "paper" / "figures"
SYSTEMS = [("full", "Full (agentic, 7B)"), ("single_pass", "Single-pass"), ("text_only", "Text-only agentic"),
           ("full_strict", "Full, strict G1 (ablation)"), ("full_gemini", "Full, Gemini 3.5 Flash-Lite")]
NAME = dict(SYSTEMS)
RUN_FILE = {"full": "full_test", "single_pass": "single_pass_test", "text_only": "text_only_test",
            "full_strict": "full_strict_test", "full_gemini": "full_gemini_test"}
# dataviz reference palette, categorical slots 1-3 (validated: scripts/validate_palette.js, light)
COLOURS = {"correct": "#2a78d6", "wrong": "#eb6834", "abstained": "#1baf7a"}
HATCH = {"correct": "", "wrong": "///", "abstained": "\\\\\\"}


def pct(x, digits=0):
    return f"{100 * x:.{digits}f}"


def ci(m, digits=0, scale=100):
    # "21 [15, 28]" from a summary interval
    if not isinstance(m, dict) or m.get("mean") is None:
        return "--"
    lo, hi = m["ci95"]
    f = lambda v: f"{scale * v:.{digits}f}"
    return f"{f(m['mean'])} [{f(lo)}, {f(hi)}]"


def plain(m, digits=2):
    return "--" if not isinstance(m, dict) or m.get("mean") is None else f"{m['mean']:.{digits}f}"


def table(path, caption, label, header, rows, align, note=None, size="\\small", fit=False):
    # fit: scale the tabular to the text width (the wide tables would run into the margin)
    lines = ["% generated by scripts/make_thesis_tables.py -- do not edit", "\\begin{table}[htbp]", "\\centering",
             size, ("\\resizebox{\\linewidth}{!}{%" if fit else ""), f"\\begin{{tabular}}{{{align}}}", "\\toprule",
             " & ".join(header) + " \\\\", "\\midrule"]
    lines += [" & ".join(str(c) for c in r) + " \\\\" for r in rows]
    lines += ["\\bottomrule", "\\end{tabular}" + ("}" if fit else "")]
    if note:
        lines += [f"\\par\\smallskip\\parbox{{0.95\\linewidth}}{{\\footnotesize {note}}}"]
    lines += [f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\end{table}", ""]
    atomic_write_text(TABLES / path, "\n".join(lines))


def judged(run):
    return {j["qid"]: j for j in read_jsonl(ROOT / "results" / "judged" / f"{RUN_FILE[run]}.jsonl")}


def runs(run):
    return {r["qid"]: r for r in read_jsonl(ROOT / "results" / "runs" / f"{RUN_FILE[run]}.jsonl")}


def main():
    s = json.loads((ROOT / "results" / "summary.json").read_text(encoding="utf-8"))
    sy = {k: s["systems"][k]["all"] for k, _ in SYSTEMS}
    mh = {k: s["systems"][k]["multihop"] for k, _ in SYSTEMS}
    comp = s["comparisons"]
    TABLES.mkdir(parents=True, exist_ok=True)

    # --- main results -------------------------------------------------------------------
    rows = []
    for k, name in SYSTEMS:
        a = sy[k]
        rows.append([name, ci(a["correct"]), ci(a["wrong"]), ci(a["abstained"]),
                     pct(a["precision_when_answering"]["mean"]), f"{a['hit_rate']['mean']:.2f}", plain(a["rf"]),
                     plain(a["aes"]), f"{a['search_calls_per_question']:.1f}", f"{a['model_calls_per_question']:.1f}"])
    table("tab_main_results.tex",
          "Outcomes on the 150 test questions (\\%, with 95\\% bootstrap intervals), precision when answering, "
          "retrieval and efficiency. Correct and wrong are judged against SPIQA's gold answer by the model judge "
          "(Section~\\ref{sec:judge}); abstained includes answers whose every claim was withheld by G2.",
          "tab:main-results",
          ["System", "Correct", "Wrong", "Abstained", "Prec.", "Hit", "RF", "AES", "Search", "Calls"],
          rows, "lccccccccc",
          note="Prec.\\ = correct / answered (\\%). Hit = the reference table or figure was retrieved. "
               "RF is undefined for text-only (it retrieves no region). Search = search-tool calls per question; "
               "Calls = model calls per question.", fit=True, size="\\scriptsize")

    # --- paired comparisons -------------------------------------------------------------
    def d(m, key):
        x = comp[m].get(key)
        if not x:
            return "--"
        mark = "$^{*}$" if x["beyond_luck"] else ""
        return f"{100 * x['diff']:+.1f} [{100 * x['ci95'][0]:+.0f}, {100 * x['ci95'][1]:+.0f}]{mark}"
    pairs = [("full - single_pass", "Full $-$ Single-pass"), ("full - text_only", "Full $-$ Text-only"),
             ("full - full_strict", "Full $-$ strict ablation"), ("full_gemini - full", "Gemini $-$ Full (7B)")]
    rows = []
    for subset, sub_name in (("all", "all 150"), ("multihop", "multi-hop 10")):
        for key, name in pairs:
            m = f"{key} ({subset})"
            rows.append([f"{name} ({sub_name})", d(m, "correct"), d(m, "wrong"), d(m, "abstained")])
    table("tab_comparisons.tex",
          "Paired differences in percentage points on the same questions, with 95\\% bootstrap intervals "
          "(10{,}000 resamples). $^{*}$: the interval excludes 0.", "tab:comparisons",
          ["Comparison", "Correct", "Wrong", "Abstained"], rows, "lccc", fit=True)

    # --- multi-hop -------------------------------------------------------------------------
    rows = [[name, mh[k]["counts"]["correct"], mh[k]["counts"]["wrong"], mh[k]["counts"]["abstained"]]
            for k, name in SYSTEMS]
    table("tab_multihop.tex",
          f"Outcomes on the multi-hop subset ({s['multihop_questions']} test questions that ask for a reason or an "
          "implication of a result: the result is in a table, the reason in the text). Counts.",
          "tab:multihop", ["System", "Correct", "Wrong", "Abstained"], rows, "lccc")

    # --- selectivity of abstention ------------------------------------------------------
    sp = judged("single_pass")
    rows, sel = [], {}
    for k in ("full", "full_strict", "full_gemini"):
        j = judged(k)
        held = [q for q in j if j[q]["outcome"] == "abstained"]
        ans = [q for q in j if j[q]["outcome"] != "abstained"]
        rate = lambda qs: sum(sp[q]["outcome"] == "correct" for q in qs) / len(qs)
        sel[k] = (rate(held), len(held), rate(ans), len(ans))
        rows.append([NAME[k], f"{pct(rate(held))} (of {len(held)})", f"{pct(rate(ans))} (of {len(ans)})"])
    table("tab_selectivity.tex",
          "Is abstention selective? Single-pass's accuracy (\\%) on the questions each system held back, and on "
          "those it answered. A selective system holds back the questions that are hard for every system.",
          "tab:selectivity", ["System", "Held back", "Answered"], rows, "lcc")

    # --- grounding (RQ3) --------------------------------------------------------------------
    rows = []
    for k, name in SYSTEMS:
        a = sy[k]
        rows.append([name, plain(a["cgs_all"]), plain(a["cgs_answered"]), pct(a["cgs_at_least_0.5"]),
                     plain(a["pointing_all"]), plain(a["pointing_answered"]), plain(a["map_auto"])])
    table("tab_grounding.tex",
          f"Grounding on the {s['annotated_boxes']} questions with hand-drawn answer boxes. CGS: best IoU of a proof "
          "box with a hand box (abstention = 0). Pointing: a proof box's centre lies inside a hand box. "
          "Ref.\\ attr.: share of published claims citing the reference table or figure (all 150 questions).",
          "tab:grounding",
          ["System", "CGS", "CGS ans.", "IoU$\\geq$0.5 (\\%)", "Point.", "Point. ans.", "Ref.\\ attr."],
          rows, "lcccccc", fit=True, size="\\scriptsize")

    # --- where the proofs point -----------------------------------------------------------
    gold = defaultdict(list)
    with open(ROOT / "eval" / "annotations.csv", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            if r["x0"]:
                gold[r["qid"]].append((int(r["page"]), tuple(float(r[c]) for c in ("x0", "y0", "x1", "y1"))))
    rows, proof = [], {}
    for k in ("full", "single_pass", "full_gemini"):
        recs = runs(k)
        n = on_ref = inside = cells = cells_in = 0
        for q, g in gold.items():
            r = recs[q]
            labels = {e["id"]: e["label"] for e in r["evidence"]}
            for b in r["boxes"]:
                n += 1
                if labels.get(b["evidence"]) != r["reference"]:
                    continue
                on_ref += 1
                hit = any(b["page"] == p and center_inside(b["bbox"], gb) for p, gb in g)
                inside += hit
                if b["cite"] == "cell":
                    cells += 1
                    cells_in += hit
        proof[k] = (n, on_ref, inside, cells, cells_in)
        rows.append([NAME[k], n, on_ref, f"{inside} ({pct(inside / on_ref)}\\%)", f"{cells_in}/{cells}"])
    table("tab_proof_sources.tex",
          "Where the proof boxes point, on the annotated questions: boxes on the reference table or figure, and "
          "how many of those have their centre inside the hand-drawn answer box.", "tab:proof-sources",
          ["System", "Proof boxes", "On the reference", "Inside the answer box", "Table cells inside"],
          rows, "lcccc", fit=True)

    # --- the outcome figure -----------------------------------------------------------------
    FIGURES.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"font.family": "serif", "font.size": 9, "hatch.linewidth": 0.6})
    fig, ax = plt.subplots(figsize=(6.2, 2.7))
    order = list(reversed(SYSTEMS))
    for i, (k, name) in enumerate(order):
        left = 0.0
        for outcome in ("correct", "wrong", "abstained"):
            v = sy[k][outcome]["mean"]
            ax.barh(i, v, left=left, height=0.62, color=COLOURS[outcome], hatch=HATCH[outcome],
                    edgecolor="white", linewidth=1.2, label=outcome.capitalize() if i == 0 else None)
            if v >= 0.06:
                ax.text(left + v / 2, i, f"{pct(v)}%", ha="center", va="center", fontsize=8, color="#0b0b0b",
                        bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="none", alpha=0.85))
            left += v
    ax.set_yticks(range(len(order)), [name for _, name in order])
    ax.set_xlim(0, 1)
    ax.set_xticks([0, 0.25, 0.5, 0.75, 1], ["0%", "25%", "50%", "75%", "100%"], color="#52514e")
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color("#c3c2b7")
    ax.tick_params(axis="y", length=0)
    ax.legend(ncol=3, loc="lower center", bbox_to_anchor=(0.4, 1.0), frameon=False, fontsize=8.5)
    fig.tight_layout()
    fig.savefig(FIGURES / "fig_outcomes.pdf")
    fig.savefig(FIGURES / "fig_outcomes.png", dpi=150)

    # --- numbers quoted in the text ------------------------------------------------------
    def m(key, k, field="mean"):
        return pct(sy[k][key][field])
    jc = s["judge_check"]
    c = lambda key: comp[key]
    macros = {
        "FullCorrect": m("correct", "full"), "FullWrong": m("wrong", "full"), "FullAbstain": m("abstained", "full"),
        "SPCorrect": m("correct", "single_pass"), "SPWrong": m("wrong", "single_pass"),
        "TOCorrect": m("correct", "text_only"), "TOWrong": m("wrong", "text_only"),
        "TOAbstain": m("abstained", "text_only"),
        "GemCorrect": m("correct", "full_gemini"), "GemWrong": m("wrong", "full_gemini"),
        "GemAbstain": m("abstained", "full_gemini"),
        "StrictAbstain": m("abstained", "full_strict"),
        "FullPrec": pct(sy["full"]["precision_when_answering"]["mean"]),
        "SPPrec": pct(sy["single_pass"]["precision_when_answering"]["mean"]),
        "GemPrec": pct(sy["full_gemini"]["precision_when_answering"]["mean"]),
        "DiffWrongSP": f"{-100 * c('full - single_pass (all)')['wrong']['diff']:.1f}",
        "DiffCorrectSP": f"{-100 * c('full - single_pass (all)')['correct']['diff']:.1f}",
        "JudgeAgree": f"{round(jc['agreement'] * jc['graded'])}/{jc['graded']}",
        "JudgeKappa": f"{jc['cohen_kappa']:.2f}", "JudgeUnsure": str(jc["unsure"]),
        "SelFullHeld": pct(sel["full"][0]), "SelFullAns": pct(sel["full"][2]),
        "SelGemHeld": pct(sel["full_gemini"][0]), "SelGemAns": pct(sel["full_gemini"][2]),
        "ProofOnRefFull": str(proof["full"][1]), "ProofBoxesFull": str(proof["full"][0]),
        "ProofInsideFull": pct(proof["full"][2] / proof["full"][1]),
        "CellsFull": f"{proof['full'][4]}/{proof['full'][3]}", "CellsSP": f"{proof['single_pass'][4]}/{proof['single_pass'][3]}",
        "CGSFull": plain(sy["full"]["cgs_all"]), "PointFullAns": plain(sy["full"]["pointing_answered"]),
        "MultihopN": str(s["multihop_questions"]), "AnnotatedN": str(s["annotated_boxes"]),
    }
    atomic_write_text(ROOT / "paper" / "numbers.tex",
                      "% generated by scripts/make_thesis_tables.py -- do not edit\n"
                      + "".join(f"\\newcommand{{\\n{k}}}{{{v}}}\n" for k, v in macros.items()))
    print("tables:", ", ".join(sorted(p.name for p in TABLES.glob("tab_*.tex"))))
    print("figure: paper/figures/fig_outcomes.pdf; macros: paper/numbers.tex")


if __name__ == "__main__":
    main()
