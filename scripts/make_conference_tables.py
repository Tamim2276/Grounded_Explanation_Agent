# The conference paper's tables, numbers and figure (IEEE two-column), generated from the results.
#
#   python scripts/score.py && python scripts/make_conference_tables.py
#
# Writes paper_conference/tables/*.tex, paper_conference/numbers.tex and
# paper_conference/figures/fig_outcomes.pdf. The figure is drawn at its printed size (one
# column, 3.45 in) so that no text in it is smaller than 8 pt.
import json
import shutil

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from gea import config as cfg
from gea.safeio import atomic_write_text

ROOT = cfg.PROJECT_ROOT
OUT = ROOT / "paper_conference"
SYSTEMS = [("full", "Full (7B)"), ("single_pass", "Single-pass"), ("text_only", "Text-only"),
           ("full_strict", "Strict G1"), ("full_gemini", "Full (Gemini)")]
COLOURS = {"correct": "#2a78d6", "wrong": "#eb6834", "abstained": "#1baf7a"}   # dataviz slots 1-3, validated
HATCH = {"correct": "", "wrong": "///", "abstained": "\\\\\\"}


def pct(x):
    return f"{100 * x:.0f}"


def ci(m):
    lo, hi = m["ci95"]
    return f"{pct(m['mean'])} [{pct(lo)}, {pct(hi)}]"


def plain(m, digits=2):
    return "--" if not isinstance(m, dict) or m.get("mean") is None else f"{m['mean']:.{digits}f}"


def write_table(name, body_lines):
    atomic_write_text(OUT / "tables" / name,
                      "% generated by scripts/make_conference_tables.py -- do not edit\n" + "\n".join(body_lines) + "\n")


def main():
    s = json.loads((ROOT / "results" / "summary.json").read_text(encoding="utf-8"))
    sy = {k: s["systems"][k]["all"] for k, _ in SYSTEMS}
    comp = s["comparisons"]
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    (OUT / "figures").mkdir(parents=True, exist_ok=True)

    # Table: outcomes (one column, so that it can stand right after the paragraph describing it)
    rows = [f"{name} & {ci(sy[k]['correct'])} & {ci(sy[k]['wrong'])} & {ci(sy[k]['abstained'])} & "
            f"{pct(sy[k]['precision_when_answering']['mean'])} \\\\" for k, name in SYSTEMS]
    write_table("tab_outcomes.tex", [
        "\\setlength{\\tabcolsep}{3.5pt}",
        "\\begin{tabular}{lcccc}", "\\toprule",
        "System & Correct & Wrong & Abstained & Prec. \\\\",
        "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"])

    # Table: paired differences against the full 7B agent
    def d(key, metric):
        x = comp[key][metric]
        star = "$^{*}$" if x["beyond_luck"] else ""
        return f"${100 * x['diff']:+.1f}${star}"
    pairs = [("full - single_pass (all)", "Full $-$ Single-pass"), ("full - text_only (all)", "Full $-$ Text-only"),
             ("full - full_strict (all)", "Full $-$ Strict G1"), ("full_gemini - full (all)", "Gemini $-$ Full (7B)"),
             ("full - single_pass (multihop)", "Full $-$ Single-pass, MH"),
             ("full - text_only (multihop)", "Full $-$ Text-only, MH")]
    rows = [f"{name} & {d(key, 'correct')} & {d(key, 'wrong')} & {d(key, 'abstained')} \\\\" for key, name in pairs]
    write_table("tab_differences.tex", [
        "\\begin{tabular}{lccc}", "\\toprule", "Comparison & Correct & Wrong & Abstained \\\\", "\\midrule",
        *rows[:4], "\\midrule", *rows[4:], "\\bottomrule", "\\end{tabular}"])

    # Table: grounding on the annotated questions
    rows = [f"{name} & {plain(sy[k]['cgs_all'])} & {plain(sy[k]['pointing_all'])} & "
            f"{plain(sy[k]['pointing_answered'])} & {plain(sy[k]['map_auto'])} \\\\"
            for k, name in SYSTEMS if k != "full_strict"]
    write_table("tab_grounding.tex", [
        "\\begin{tabular}{lcccc}", "\\toprule", "System & CGS & Point. & Point.\\ (ans.) & Ref.\\ attr. \\\\",
        "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"])

    # Figure: outcomes, drawn at its printed size
    # pdf.fonttype 42: embed TrueType fonts. matplotlib's default (3) writes Type 3 fonts, which
    # IEEE (PDF eXpress) and the conference rules forbid.
    plt.rcParams.update({"font.family": "serif", "font.serif": ["Times New Roman", "Nimbus Roman", "DejaVu Serif"],
                         "font.size": 8.5, "hatch.linewidth": 0.6, "pdf.fonttype": 42, "ps.fonttype": 42})
    fig, ax = plt.subplots(figsize=(3.45, 2.15))
    order = list(reversed(SYSTEMS))
    for i, (k, name) in enumerate(order):
        left = 0.0
        for outcome in ("correct", "wrong", "abstained"):
            v = sy[k][outcome]["mean"]
            ax.barh(i, v, left=left, height=0.64, color=COLOURS[outcome], hatch=HATCH[outcome],
                    edgecolor="white", linewidth=1.0, label=outcome.capitalize() if i == 0 else None)
            if v >= 0.08:
                ax.text(left + v / 2, i, pct(v), ha="center", va="center", fontsize=8.5, color="#0b0b0b",
                        bbox=dict(boxstyle="round,pad=0.12", fc="white", ec="none", alpha=0.9))
            left += v
    ax.set_yticks(range(len(order)), [name for _, name in order])
    ax.set_xlim(0, 1)
    ax.set_xticks([0, 0.25, 0.5, 0.75, 1], ["0", "25", "50", "75", "100"])
    ax.set_xlabel("Share of the 150 test questions (%)")
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color("#c3c2b7")
    ax.tick_params(axis="y", length=0)
    ax.legend(ncol=3, loc="lower center", bbox_to_anchor=(0.42, 1.0), frameon=False, handlelength=1.6,
              columnspacing=1.0)
    fig.tight_layout(pad=0.3)
    fig.savefig(OUT / "figures" / "fig_outcomes.pdf")
    fig.savefig(OUT / "figures" / "fig_outcomes.png", dpi=200)

    # The numbers quoted in the text: the thesis's macros (same results, same names)
    shutil.copyfile(ROOT / "paper" / "numbers.tex", OUT / "numbers.tex")
    print("conference tables, figure and numbers written to", OUT)


if __name__ == "__main__":
    main()
